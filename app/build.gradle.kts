    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  signingConfigs {
    create("release") {
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD")
      keyAlias = "upload"
      keyPassword = System.getenv("KEY_PASSWORD")
    }
    create("debugConfig") {
      val keystoreFile = file("${rootDir}/debug.keystore")
      val base64File = file("${rootDir}/debug.keystore.base64")

      if (!keystoreFile.exists() && base64File.exists()) {
        try {
          val base64Bytes = base64File.readBytes()
          val cleanedBase64 = String(base64Bytes).replace("\\s".toRegex(), "")
          val decodedBytes = Base64.getDecoder().decode(cleanedBase64)
          keystoreFile.writeBytes(decodedBytes)
        } catch (e: Exception) {
          println("Warning: Failed to decode debug.keystore from base64: ${e.message}")
        }
      }

      if (keystoreFile.exists()) {
        storeFile = keystoreFile
        storePassword = "android"
        keyAlias = "androiddebugkey"
        keyPassword = "android"
      } else {
        val defaultDebugKeystore = file(System.getProperty("user.home") + "/.android/debug.keystore")
        if (defaultDebugKeystore.exists()) {
          storeFile = defaultDebugKeystore
          storePassword = "android"
          keyAlias = "androiddebugkey"
          keyPassword = "android"
        } else {
          storeFile = keystoreFile
          storePassword = "android"
          keyAlias = "androiddebugkey"
          keyPassword = "android"
        }
      }
    }
  }

